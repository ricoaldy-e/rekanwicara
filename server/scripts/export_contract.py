"""Export synthetic API examples for the app's TypeScript and Jest contract checks.

Run from server/: .venv/Scripts/python.exe -m scripts.export_contract
"""

import json
from pathlib import Path

from app.api.mock import build_analyze_mock, build_calibrate_mock
from app.api.schemas import ErrorDetail, ErrorResponse, HealthResponse
from app.content.loader import load_content

FIXTURE = Path(__file__).resolve().parents[2] / "app/test-fixtures/api-contract.ts"


def render_contract() -> str:
    content = load_content()
    cases = [
        ("l0_hold_a", "hijau"),
        ("l1_a", "kuning"),
        ("l2_ma", "merah"),
        ("l3_mama", "hijau"),
        ("l3_mama", "merah"),
        ("l1_a", "retry"),
    ]
    payload = {
        "health": HealthResponse(
            engine_version="0.1.0", scorer_mode="rules", mock_mode=False
        ).model_dump(mode="json"),
        "items": [
            item.model_dump(mode="json") for item in content.items_by_id.values() if item.active
        ],
        "analyses": [
            build_analyze_mock(content.items_by_id[item], variant, "rules", "0.1.0", 12).model_dump(
                mode="json"
            )
            for item, variant in cases
        ],
        "calibrations": [
            build_calibrate_mock(step, variant, "0.1.0").model_dump(mode="json")
            for step in ("rest", "vowel_a", "vowel_i", "vowel_u")
            for variant in ("hijau", "retry")
        ],
        "error": ErrorResponse(
            detail=ErrorDetail(
                code="model_video_not_found", message="No model video for this item."
            )
        ).model_dump(mode="json"),
    }
    lines = [
        "// Generated by server/scripts/export_contract.py; synthetic values, no recordings.",
        "import type {",
        "  AnalyzeResponse, CalibrateResponse, ErrorResponse, HealthResponse, Item,",
        "} from '../src/api/types';",
        "",
        "export const contract = {",
        *[f"  {key}: {json.dumps(value, ensure_ascii=False)}," for key, value in payload.items()],
        "} satisfies {",
        "  health: HealthResponse; items: Item[]; analyses: AnalyzeResponse[];",
        "  calibrations: CalibrateResponse[]; error: ErrorResponse;",
        "};",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(render_contract(), encoding="utf-8")
    print("Exported synthetic API contract fixture.")
